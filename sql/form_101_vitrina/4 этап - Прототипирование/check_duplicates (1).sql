-- Проверка на дубли по первичному ключу
SELECT regn, plan, num_sc, dt, COUNT(*) AS cnt
FROM bank.f101_mart
GROUP BY regn, plan, num_sc, dt
HAVING COUNT(*) > 1;

-- Выбран составной ключ (regn, plan, num_sc, dt)
-- regn - регистрационный номер банка (одинаков для всех строк)
-- plan - глава плана счетов (А/Б/В/Г)
-- num_sc - номер балансового счета второго порядка (5 цифр)
-- dt - отчетная дата
-- для одного банка не может быть несколько строк с одинаковым сочетанием 
-- главы и номера счета в один отчётный период